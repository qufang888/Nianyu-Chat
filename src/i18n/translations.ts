export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>
): string {
  // 回退链：目标语言 → zh → en → 原始键名（保证任何语言下不会裸露键名）
  let str = translations[lang]?.[key] ?? translations.zh[key] ?? translations.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}
