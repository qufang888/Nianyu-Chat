LANGS = ['zh', 'en', 'de', 'es', 'fr', 'ja', 'ko', 'pt', 'ru', 'zh-Hant']
KEYS = list(T['zh'].keys())
PH = re.compile(r'\{(\w+)\}')
PLACEHOLDER_KEYS = {'characters.added': {'name'}, 'characters.importOk': {'n'},
                    'characters.menuBackTo': {'name'}}


def js_str(s: str) -> str:
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def check():
    """每个语言：键集合一致、无空值、占位符一致"""
    for lang in LANGS:
        assert set(T[lang].keys()) == set(KEYS), '%s 键集合不一致' % lang
        for k in KEYS:
            v = T[lang][k]
            assert v and v.strip(), '%s/%s 为空' % (lang, k)
            want = PLACEHOLDER_KEYS.get(k, set())
            got = set(PH.findall(v))
            assert got == want, '%s/%s 占位符不一致: %s != %s' % (lang, k, got, want)


def insert_after(lines, anchor, new_lines, nth=1):
    """在锚点第 nth 次出现的那一行之后插入 new_lines。"""
    out = []
    seen = 0
    hit = False
    for line in lines:
        out.append(line)
        if anchor in line:
            seen += 1
            if seen == nth and not hit:
                out.extend(new_lines)
                hit = True
    return out, hit


